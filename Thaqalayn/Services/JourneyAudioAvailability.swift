//
//  JourneyAudioAvailability.swift
//  Thaqalayn
//
//  On-demand delivery for premium journey narration (Phase 4.2). The two free journeys
//  (Yaqin, al-Fatiha) ship bundled in the app; every other journey's narration mp3s are
//  Apple-hosted On-Demand Resources (ODR), tagged by journey id, downloaded on the first
//  Listen and then cached by iOS for offline replay. This service owns the NSBundleResourceRequest
//  lifecycle: it reports whether a journey is bundled / downloaded / needs a download / is
//  downloading, drives the "Preparing this journey…" state, and keeps the request alive so
//  the downloaded mp3s resolve through the bundle while the journey plays.
//
//  The ODR tag for a journey's English narration is exactly its id (e.g. "surah-rahman"); its
//  Urdu narration is a separate pack tagged "<id>-ur" - for the free journeys too, since only
//  their English is bundled. Each tagged pack is SELF-CONTAINED (all the narration strings that
//  journey speaks in that language, including shared connectors), so a journey downloads and
//  plays as one independent unit with no cross-pack dependencies.
//

import Foundation

@MainActor
final class JourneyAudioAvailability: ObservableObject {
    static let shared = JourneyAudioAvailability()
    private init() {}

    /// Journeys whose English narration ships inside the app binary - always available, never
    /// an ODR download. Mirrors the free tier gated by PremiumManager (Yaqin + surah-fatiha).
    nonisolated static let bundledJourneyIds: Set<String> = ["yaqin", "surah-fatiha"]

    /// The languages a journey can be narrated in.
    nonisolated static let narrationLanguages: [CommentaryLanguage] = [.english, .urdu]

    nonisolated static func isBundled(_ journeyId: String, language: CommentaryLanguage = .english) -> Bool {
        language == .english && bundledJourneyIds.contains(journeyId)
    }

    /// The ODR tag of a journey's narration in a language - also its pack's bundle subdirectory.
    nonisolated static func packTag(_ journeyId: String, language: CommentaryLanguage) -> String {
        language == .english ? journeyId : "\(journeyId)-\(language.rawValue)"
    }

    /// Narration packs fully available to Listen, by tag (`packTag`): the bundled free tier plus
    /// every complete on-demand pack, English and Urdu. Loaded once from the bundled
    /// `journey_audio_ready.json` (regenerated by package_journey_odr.py). Listen is gated on
    /// this so a journey whose audio isn't finished yet never offers a half-silent Listen - in
    /// that language it just doesn't appear.
    nonisolated static let audioReadyJourneyIds: Set<String> = {
        guard let url = Bundle.main.url(forResource: "journey_audio_ready", withExtension: "json"),
              let data = try? Data(contentsOf: url),
              let ids = try? JSONDecoder().decode([String].self, from: data) else {
            return bundledJourneyIds   // fail safe: at least the bundled free journeys are playable
        }
        return Set(ids)
    }()

    /// Whether a journey's narration is complete and ready to Listen in a language (English
    /// gates the Listen entry).
    nonisolated static func isAudioReady(_ journeyId: String, language: CommentaryLanguage = .english) -> Bool {
        audioReadyJourneyIds.contains(packTag(journeyId, language: language))
    }

    /// The languages a journey can be heard in right now, English first.
    nonisolated static func readyLanguages(for journeyId: String) -> [CommentaryLanguage] {
        narrationLanguages.filter { isAudioReady(journeyId, language: $0) }
    }

    enum State: Equatable {
        case bundled                        // ships in the app - instant
        case downloaded                     // ODR pack present on device
        case needsDownload
        case downloading(progress: Double)
        case failed(String)
    }

    /// Live state per pack tag, for any UI that wants to reflect it (the Listen entry, a
    /// future "downloaded journeys" screen). Bundled journeys are reported without a lookup.
    @Published private(set) var states: [String: State] = [:]

    /// Active ODR requests by pack tag, kept alive (accessing) while a journey is in use so its
    /// mp3s keep resolving through Bundle.main. Released in `release(journeyId:language:)` when
    /// playback ends.
    private var requests: [String: NSBundleResourceRequest] = [:]

    func state(for journeyId: String, language: CommentaryLanguage = .english) -> State {
        if Self.isBundled(journeyId, language: language) { return .bundled }
        return states[Self.packTag(journeyId, language: language)] ?? .needsDownload
    }

    /// Ensure a journey's narration in a language is on device, ready to resolve through the
    /// bundle. Bundled journeys return instantly. Otherwise this begins (or reuses) the ODR
    /// request for the pack's tag, reporting download progress via `onProgress` and the
    /// published `states`, and returns whether the pack is now available. The request is
    /// retained so the resources stay accessible for playback; call `release` when done.
    func ensureAvailable(journeyId: String, language: CommentaryLanguage = .english,
                         onProgress: @escaping (Double) -> Void = { _ in }) async -> Bool {
        if Self.isBundled(journeyId, language: language) { return true }
        let tag = Self.packTag(journeyId, language: language)

        // A live, still-accessing request means the pack is ready right now.
        if requests[tag] != nil, case .downloaded = states[tag] { return true }

        let req = requests[tag] ?? NSBundleResourceRequest(tags: [tag])
        req.loadingPriority = NSBundleResourceRequestLoadingPriorityUrgent
        requests[tag] = req

        // Already downloaded (cached by iOS from a previous Listen)? Access without a network hit.
        if await req.conditionallyBeginAccessingResources() {
            states[tag] = .downloaded
            onProgress(1)
            return true
        }

        states[tag] = .downloading(progress: 0)
        onProgress(0)
        // Progress fires on an arbitrary thread; marshal to main for the published state + callback.
        // Capture the request's identity (Sendable), not the request itself, so a stale
        // observation from a superseded request is ignored.
        let reqId = ObjectIdentifier(req)
        let observation = req.progress.observe(\.fractionCompleted) { [weak self] progress, _ in
            let p = progress.fractionCompleted
            Task { @MainActor in
                guard let self, let current = self.requests[tag],
                      ObjectIdentifier(current) == reqId else { return }
                self.states[tag] = .downloading(progress: p)
                onProgress(p)
            }
        }
        defer { observation.invalidate() }

        do {
            try await req.beginAccessingResources()
            states[tag] = .downloaded
            onProgress(1)
            return true
        } catch {
            // Failed download: drop the request so a retry starts clean.
            req.endAccessingResources()
            requests[tag] = nil
            states[tag] = .failed(error.localizedDescription)
            return false
        }
    }

    /// End access to a journey's ODR pack in a language when playback stops. iOS keeps the
    /// bytes cached (eligible for purging only under storage pressure), so a later Listen
    /// re-accesses fast - offline if still cached. Bundled journeys are a no-op.
    func release(journeyId: String, language: CommentaryLanguage = .english) {
        let tag = Self.packTag(journeyId, language: language)
        guard let req = requests[tag] else { return }
        req.endAccessingResources()
        requests[tag] = nil
        states[tag] = .needsDownload
    }
}
